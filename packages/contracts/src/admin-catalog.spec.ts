import {describe,expect,it} from 'vitest';
import {
  adminCatalogAuthorCreatedSchema,adminCatalogAuthorPageSchema,
  adminCatalogSearchQuerySchema,adminCatalogWorkCreatedSchema,
  adminCatalogWorkPageSchema,authorCreateSchema,workCreateSchema,
} from './index.js';

const id='a7d09a10-d218-4e7f-8871-cb93dab6bf23';
const page={items:[{id,originalTitle:'Test Work',originalLanguage:'tr',publicationStatus:'draft'}],
  nextCursor:null};

describe('admin-only canonical metadata search contracts',()=>{
  it('requires a query and rejects user/role selectors and unbounded pagination',()=>{
    expect(adminCatalogSearchQuerySchema.parse({q:'  Folio  '})).toEqual({
      q:'Folio',limit:20,
    });
    expect(adminCatalogSearchQuerySchema.parse({q:'work',limit:'50',cursor:id}))
      .toEqual({q:'work',limit:50,cursor:id});
    for(const invalid of [
      {},{q:''},{q:'   '},{q:'a'.repeat(121)},
      {q:'title',limit:0},{q:'title',limit:'00'},
      {q:'title',limit:51},{q:'title',limit:'999'},
      {q:'title',limit:1.1},{q:'title',cursor:'malformed'},
      {q:'title',userId:id},{q:'title',role:'superadmin'},
      {q:'title',country:'US'}, {q:['title']},
    ]){
      expect(adminCatalogSearchQuerySchema.safeParse(invalid).success).toBe(false);
    }
  });

  it('returns strict work/author metadata without private bodies or session identifiers',()=>{
    expect(adminCatalogWorkPageSchema.parse(page)).toEqual(page);
    const authors={items:[{id,canonicalName:'A Writer',sortName:'Writer, A'}],
      nextCursor:null};
    expect(adminCatalogAuthorPageSchema.parse(authors)).toEqual(authors);
    for(const invalid of [
      {...page,items:[{...page.items[0],body:'PRIVATE BOOK CONTENT'}]},
      {...page,items:[{...page.items[0],ownerId:id}]},
      {...page,items:[{...page.items[0],email:'private@example.com'}]},
      {...page,sessionToken:'A'.repeat(43)},
      {...page,items:[{...page.items[0],originalLanguage:'fr'}]},
      {...page,nextCursor:'not-a-uuid'},
      {...page,items:Array.from({length:51},()=>page.items[0])},
    ]){
      expect(adminCatalogWorkPageSchema.safeParse(invalid).success).toBe(false);
    }
    expect(adminCatalogAuthorPageSchema.safeParse({
      ...authors,items:[{...authors.items[0],phone:'private'}],
    }).success).toBe(false);
  });
  it('accepts only strict draft write payloads and minimal opaque create replies',()=>{
    const authorId=id;
    const goodAuthor={canonicalName:'  A Writer  ',
      aliases:[{name:'A Name',locale:'en'}],
      externalIds:[{source:'local',externalId:'123'}]};
    expect(authorCreateSchema.parse(goodAuthor).canonicalName).toBe('A Writer');
    for(const invalid of [
      {...goodAuthor,actorId:id}, {...goodAuthor,userId:id},
      {...goodAuthor,role:'superadmin'},
      {...goodAuthor,publicationStatus:'published'},
      {...goodAuthor,aliases:[{name:'A',userId:id}]},
      {canonicalName:'  '},
    ]){
      expect(authorCreateSchema.safeParse(invalid).success).toBe(false);
    }
    const validWork={
      originalTitle:'A Draft',originalLanguage:'tr' as const,
      authors:[{authorId}],
      titles:[{language:'en' as const,title:'An Edition',kind:'translation' as const}],
      editions:[{language:'en' as const,label:'Translation',
        contributors:[{authorId,role:'translator' as const}]}],
    };
    expect(workCreateSchema.safeParse(validWork).success).toBe(true);
    for(const invalid of [
      {...validWork,publicationStatus:'published'},
      {...validWork,ownerId:id},
      {...validWork,content:'AUTOGENERATED'},
      {...validWork,authors:[]},
      {...validWork,authors:[{authorId},{authorId}]},
      {...validWork,authors:[{authorId,contribution:'editor'}]},
      {...validWork,editions:[{language:'en',label:'Edition',status:'published'}]},
    ]){
      expect(workCreateSchema.safeParse(invalid).success).toBe(false);
    }
    expect(adminCatalogAuthorCreatedSchema.parse({id})).toEqual({id});
    expect(adminCatalogWorkCreatedSchema.parse({id,publicationStatus:'draft'}))
      .toEqual({id,publicationStatus:'draft'});
    expect(adminCatalogWorkCreatedSchema.safeParse({
      id,publicationStatus:'published',
    }).success).toBe(false);
    expect(adminCatalogWorkCreatedSchema.safeParse({
      id,publicationStatus:'draft',sessionToken:'SECRET',
    }).success).toBe(false);
    expect(adminCatalogAuthorCreatedSchema.safeParse({id,userId:id}).success)
      .toBe(false);
  });
});
